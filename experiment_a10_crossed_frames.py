"""
Experiment A10 - Crossed attribution frame: source noun x adjective x reporting verb
(added 2026-09-10, third adversarial review, blocker B1). Pre-registered in
PREREGISTRO_A10_A11_2026-09-10.md before the first inference.

A9 varied whole frames, so its 0.73 and 0.93 are differences between two concrete
templates, not a decomposition into "credibility" and "factivity". Here the frame is
generated by the full crossing of three factors, with the determiner fixed:

    noun      : document (neutral)      | pamphlet (low credibility)
    adjective : none                    | "disputed"
    verb      : states | claims | confirms

2 x 2 x 3 = 12 frames x 2 polarities (X, not-X) x 20 items = 480 sentences, each scored
by both heads against the bare claim X. Content is taken verbatim from the released
CONFLICT_ITEMS, exactly as in A9.

Registered contrasts (paired by item, verb held fixed unless stated):
  Q1 adjective, isolated : "The pamphlet states X"  - "The disputed pamphlet states X"
                           "The document states X"  - "The disputed document states X"
  Q2 noun, isolated      : "The document states X"  - "The pamphlet states X"
  Q3 interaction         : difference of the two Q1 differences
  Q4 verb under fixed source : confirms - claims within each of the four sources
  Q5 polarity-blind contradiction cue : on SUPPORTING content X, count of items with
                           contradiction_B >= 0.15 for each source (verb "states")

Output: validation_results_a10.csv, validation_summary_a10.txt
"""
from __future__ import annotations
import csv, os, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = HERE
sys.path.insert(0, HERE)
from experiment_a2_conflicting_evidence import MODEL_A, MODEL_B, CONFLICT_ITEMS
from experiment_a9_attribution_frames import that_clause  # same content extraction as A9
from dual_nli import build_pipe, nli_scores

OUT_CSV = os.path.join(ROOT, "validation_results_a10.csv")
OUT_TXT = os.path.join(ROOT, "validation_summary_a10.txt")

NOUNS = {"document": "document", "pamphlet": "pamphlet"}
ADJ = {"plain": "", "disputed": "disputed "}
VERBS = ["states", "claims", "confirms"]
PROPER = {"Paris", "Einstein", "Mount", "Shakespeare", "Cuba", "Tokyo", "Earth"}


def frame_id(noun: str, adj: str, verb: str) -> str:
    return f"{adj}_{noun}_{verb}"


def render(noun: str, adj: str, verb: str, content: str) -> str:
    c = content
    if c[:1].isupper() and c.split()[0] not in PROPER:
        c = c[0].lower() + c[1:]
    s = f"The {ADJ[adj]}{NOUNS[noun]} {verb} that {c}"
    s = s[0].upper() + s[1:]
    return s if s.endswith(".") else s + "."


def main() -> None:
    print("Loading models...")
    pa, pb = build_pipe(MODEL_A), build_pipe(MODEL_B)
    rows = []
    for i, (sup, ref, claim) in enumerate(CONFLICT_ITEMS, 1):
        notx = that_clause(ref)
        if i == 5:  # same special case as A9: item 5's refutation is carried by the verb "denies"
            notx = "photosynthesis does not convert sunlight into chemical energy"
        content = {"X": claim.rstrip("."), "notX": notx.rstrip(".")}
        for pol, base in content.items():
            for noun in NOUNS:
                for adj in ADJ:
                    for verb in VERBS:
                        prem = render(noun, adj, verb, base)
                        a = nli_scores(pa, prem, claim)
                        b = nli_scores(pb, prem, claim)
                        rows.append({
                            "item": i, "polarity": pol, "noun": noun, "adjective": adj,
                            "verb": verb, "frame": frame_id(noun, adj, verb), "premise": prem,
                            "entA": round(a["entailment"], 4), "neuA": round(a["neutral"], 4),
                            "conA": round(a["contradiction"], 4),
                            "entB": round(b["entailment"], 4), "conB": round(b["contradiction"], 4),
                        })
        print(f"  item {i}/20 done", flush=True)

    with open(OUT_CSV, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader()
        for r in rows: w.writerow(r)

    idx = {(r["item"], r["polarity"], r["frame"]): r for r in rows}
    L = ["Experiment A10 - crossed source x verb (pre-registered 2026-09-10)", ""]
    L.append(f"{'pol':<5} {'frame':<26} {'entA':>7} {'neuA':>7} {'conA':>7} {'entB':>7} {'conB':>7} {'conB>=.15':>10}")
    for pol in ("X", "notX"):
        for noun in NOUNS:
            for adj in ADJ:
                for verb in VERBS:
                    f = frame_id(noun, adj, verb)
                    cell = [idx[(i, pol, f)] for i in range(1, 21)]
                    m = [statistics.mean(r[k] for r in cell) for k in ("entA", "neuA", "conA", "entB", "conB")]
                    n = sum(1 for r in cell if r["conB"] >= 0.15)
                    L.append(f"{pol:<5} {f:<26} " + " ".join(f"{v:7.3f}" for v in m) + f" {n:>7}/20")
    L.append("")

    def paired(pol, fa, fb, key="entA"):
        d = [idx[(i, pol, fa)][key] - idx[(i, pol, fb)][key] for i in range(1, 21)]
        return statistics.mean(d), min(d), max(d), sum(1 for v in d if v > 0), d

    def boot_ci(d, n=5000, seed=7):
        import random
        rng = random.Random(seed)
        ms = sorted(statistics.mean(rng.choice(d) for _ in d) for _ in range(n))
        return ms[int(0.025 * n)], ms[int(0.975 * n)]

    L.append("Q1 adjective, isolated (entailment A on X, verb=states):")
    q1 = {}
    for noun in NOUNS:
        m, lo, hi, pos, d = paired("X", frame_id(noun, "plain", "states"), frame_id(noun, "disputed", "states"))
        ci = boot_ci(d); q1[noun] = d
        L.append(f"  plain-{noun} minus disputed-{noun}: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] range [{lo:+.3f},{hi:+.3f}] positive {pos}/20"
                 f"  -> criterion 1 {'MET' if (m >= 0.10 and pos >= 15) else 'NOT MET'}")
    L.append("Q2 noun, isolated (entailment A on X, verb=states, no adjective):")
    m, lo, hi, pos, d = paired("X", frame_id("document", "plain", "states"), frame_id("pamphlet", "plain", "states"))
    ci = boot_ci(d)
    L.append(f"  document minus pamphlet: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] range [{lo:+.3f},{hi:+.3f}] positive {pos}/20")
    L.append("Q3 interaction adjective x noun (difference of the two Q1 differences):")
    dd = [q1["document"][k] - q1["pamphlet"][k] for k in range(20)]
    ci = boot_ci(dd)
    L.append(f"  mean {statistics.mean(dd):+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}]"
             f"  -> additivity {'MET' if (abs(statistics.mean(dd)) < 0.10 and ci[0] <= 0 <= ci[1]) else 'NOT MET (interaction)'}")
    L.append("Q4 verb: confirms minus claims (entailment A on X), within each source:")
    ok4 = True
    for noun in NOUNS:
        for adj in ADJ:
            m, lo, hi, pos, d = paired("X", frame_id(noun, adj, "confirms"), frame_id(noun, adj, "claims"))
            ci = boot_ci(d)
            if not (m >= 0.10): ok4 = False
            L.append(f"  {adj}-{noun}: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] positive {pos}/20")
    L.append(f"  -> factivity as a separate factor: {'MET' if ok4 else 'NOT MET'} (needs >= 0.10 under all four sources)")
    L.append("Q5 polarity-blind contradiction cue on SUPPORTING content X (verb=states):")
    for noun in NOUNS:
        for adj in ADJ:
            f = frame_id(noun, adj, "states")
            cell = [idx[(i, "X", f)] for i in range(1, 21)]
            L.append(f"  {f:<26} mean conB {statistics.mean(r['conB'] for r in cell):.3f}   conB>=.15 in {sum(1 for r in cell if r['conB'] >= 0.15)}/20")
    txt = "\n".join(L)
    open(OUT_TXT, "w", encoding="utf-8").write(txt)
    print(txt)
    print("Wrote", OUT_CSV, OUT_TXT)


if __name__ == "__main__":
    main()
