"""
Experiment A10 - Crossed attribution frame: source noun x adjective x reporting verb
(added 2026-09-10, third adversarial review, blocker B1). Pre-registered in
PREREGISTRO_A10_A11_2026-09-10.md before the first inference.

A9 varied whole frames, so its 0.73 and 0.93 are differences between two concrete
templates, not a decomposition into "credibility" and "factivity". Here the frame is
generated by the full crossing of three factors, with the determiner fixed:

    noun      : document (neutral)      | pamphlet (low credibility)
    adjective : none                    | "disputed"
    verb      : states | claims | confirms

2 x 2 x 3 = 12 frames x 2 polarities (X, not-X) x 20 items = 480 sentences, each scored
by both heads against the bare claim X. Content is taken verbatim from the released
CONFLICT_ITEMS, exactly as in A9. The two heads are loaded one at a time (the second is
built only after the first is released), so peak memory is one model, not two.

Registered contrasts (paired by item, verb held fixed unless stated):
  Q1 adjective, isolated : "The pamphlet states X"  - "The disputed pamphlet states X"
                           "The document states X"  - "The disputed document states X"
  Q2 noun, isolated      : "The document states X"  - "The pamphlet states X"
  Q3 interaction         : difference of the two Q1 differences
  Q4 verb under fixed source : confirms - claims within each of the four sources
  Q5 polarity-blind contradiction cue : on SUPPORTING content X, count of items with
                           contradiction_B >= 0.15 for each source (verb "states")

Output: validation_results_a10.csv, validation_summary_a10.txt
Run: python experiment_a10_crossed_frames.py            (both heads, one at a time)
     python experiment_a10_crossed_frames.py --pass A   (only the first head)
     python experiment_a10_crossed_frames.py --pass B   (only the second; writes the CSV
                                                         once both checkpoints exist)
Each score is appended to a10_partial_{A,B}.jsonl as it is produced, so an interrupted run
resumes from where it stopped instead of starting over.
Rebuild the summary from the released CSV without any model: --from-csv
"""
from __future__ import annotations
import csv, gc, os, random, statistics, sys

# one BLAS thread: this script is a long sequence of single-pair calls, so extra
# threads buy no speed here and each one carries its own workspace.
os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("MKL_NUM_THREADS", "1")

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = HERE
sys.path.insert(0, HERE)
from experiment_a2_conflicting_evidence import MODEL_A, MODEL_B, CONFLICT_ITEMS
from experiment_a9_attribution_frames import that_clause  # same content extraction as A9

OUT_CSV = os.path.join(ROOT, "validation_results_a10.csv")
OUT_TXT = os.path.join(ROOT, "validation_summary_a10.txt")

NOUNS = ["document", "pamphlet"]
ADJ = {"plain": "", "disputed": "disputed "}
VERBS = ["states", "claims", "confirms"]
PROPER = {"Paris", "Einstein", "Mount", "Shakespeare", "Cuba", "Tokyo", "Earth"}


def frame_id(noun: str, adj: str, verb: str) -> str:
    return f"{adj}_{noun}_{verb}"


def render(noun: str, adj: str, verb: str, content: str) -> str:
    c = content
    if c[:1].isupper() and c.split()[0] not in PROPER:
        c = c[0].lower() + c[1:]
    s = f"The {ADJ[adj]}{noun} {verb} that {c}"
    s = s[0].upper() + s[1:]
    return s if s.endswith(".") else s + "."


def build_sentences():
    """The 480 (item, polarity, frame) cells, model-free."""
    cells = []
    for i, (sup, ref, claim) in enumerate(CONFLICT_ITEMS, 1):
        notx = that_clause(ref)
        if i == 5:  # same special case as A9: item 5's refutation is carried by the verb "denies"
            notx = "photosynthesis does not convert sunlight into chemical energy"
        for pol, base in (("X", claim.rstrip(".")), ("notX", notx.rstrip("."))):
            for noun in NOUNS:
                for adj in ADJ:
                    for verb in VERBS:
                        cells.append({"item": i, "polarity": pol, "noun": noun, "adjective": adj,
                                      "verb": verb, "frame": frame_id(noun, adj, verb),
                                      "premise": render(noun, adj, verb, base), "claim": claim})
    return cells


def part_path(tag: str) -> str:
    return os.path.join(ROOT, f"a10_partial_{tag}.jsonl")


def score_all(model_name: str, cells, keys, tag: str):
    """Load one model, score every cell, append each result immediately so the pass is resumable.

    Peak memory is one model. If the process is killed, rerunning resumes from the checkpoint.
    """
    import json
    path = part_path(tag)
    done = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                r = json.loads(line)
                done[(r["item"], r["polarity"], r["frame"])] = r
    todo = [c for c in cells if (c["item"], c["polarity"], c["frame"]) not in done]
    print(f"pass {tag}: {len(done)} cached, {len(todo)} to score", flush=True)
    if todo:
        from dual_nli import build_pipe, nli_scores
        print(f"Loading {model_name} ...", flush=True)
        pipe = build_pipe(model_name, low_memory=True)
        with open(path, "a", encoding="utf-8") as fh:
            for n, c in enumerate(todo, 1):
                sc = nli_scores(pipe, c["premise"], c["claim"])
                rec = {"item": c["item"], "polarity": c["polarity"], "frame": c["frame"]}
                for out_key, in_key in keys.items():
                    rec[out_key] = round(sc.get(in_key, 0.0), 4)
                fh.write(json.dumps(rec) + chr(10)); fh.flush()
                done[(c["item"], c["polarity"], c["frame"])] = rec
                if n % 40 == 0:
                    print(f"  {n}/{len(todo)}", flush=True)
        del pipe
        gc.collect()
        print(f"  released {model_name}", flush=True)
    for c in cells:
        r = done[(c["item"], c["polarity"], c["frame"])]
        for k in keys:
            c[k] = r[k]


def boot_ci(d, n=5000, seed=7):
    rng = random.Random(seed)
    ms = sorted(statistics.mean(rng.choice(d) for _ in d) for _ in range(n))
    return ms[int(0.025 * n)], ms[int(0.975 * n)]


def summarize(rows):
    idx = {(int(r["item"]), r["polarity"], r["frame"]): r for r in rows}
    f = lambda r, k: float(r[k])
    L = ["Experiment A10 - crossed source x verb (pre-registered 2026-09-10)", ""]
    L.append(f"{'pol':<5} {'frame':<26} {'entA':>7} {'neuA':>7} {'conA':>7} {'entB':>7} {'conB':>7} {'conB>=.15':>10}")
    for pol in ("X", "notX"):
        for noun in NOUNS:
            for adj in ADJ:
                for verb in VERBS:
                    fr = frame_id(noun, adj, verb)
                    cell = [idx[(i, pol, fr)] for i in range(1, 21)]
                    m = [statistics.mean(f(r, k) for r in cell) for k in ("entA", "neuA", "conA", "entB", "conB")]
                    n = sum(1 for r in cell if f(r, "conB") >= 0.15)
                    L.append(f"{pol:<5} {fr:<26} " + " ".join(f"{v:7.3f}" for v in m) + f" {n:>7}/20")
    L.append("")

    def paired(pol, fa, fb, key="entA"):
        d = [f(idx[(i, pol, fa)], key) - f(idx[(i, pol, fb)], key) for i in range(1, 21)]
        return statistics.mean(d), min(d), max(d), sum(1 for v in d if v > 0), d

    L.append("Q1 adjective, isolated (entailment A on X, verb=states):")
    q1 = {}
    for noun in NOUNS:
        m, lo, hi, pos, d = paired("X", frame_id(noun, "plain", "states"), frame_id(noun, "disputed", "states"))
        ci = boot_ci(d); q1[noun] = d
        L.append(f"  plain-{noun} minus disputed-{noun}: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] range [{lo:+.3f},{hi:+.3f}] "
                 f"positive {pos}/20 -> criterion 1 {'MET' if (m >= 0.10 and pos >= 15) else 'NOT MET'}")
    ok1 = all(statistics.mean(q1[n]) >= 0.10 and sum(1 for v in q1[n] if v > 0) >= 15 for n in NOUNS)
    L.append(f"  -> adjective may be named as a factor: {'YES' if ok1 else 'NO (report the source phrase as a unit)'}")

    L.append("Q2 noun, isolated (entailment A on X, verb=states, no adjective):")
    m, lo, hi, pos, d = paired("X", frame_id("document", "plain", "states"), frame_id("pamphlet", "plain", "states"))
    ci = boot_ci(d)
    L.append(f"  document minus pamphlet: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] range [{lo:+.3f},{hi:+.3f}] positive {pos}/20")

    L.append("Q3 interaction adjective x noun (difference of the two Q1 differences):")
    dd = [q1["document"][k] - q1["pamphlet"][k] for k in range(20)]
    ci3 = boot_ci(dd); m3 = statistics.mean(dd)
    add = abs(m3) < 0.10 and ci3[0] <= 0 <= ci3[1]
    L.append(f"  mean {m3:+.4f} CI[{ci3[0]:+.3f},{ci3[1]:+.3f}] -> additivity {'MET' if add else 'NOT MET (interaction)'}")

    L.append("Q4 verb: confirms minus claims (entailment A on X), within each source:")
    ok4 = True
    for noun in NOUNS:
        for adj in ADJ:
            m, lo, hi, pos, d = paired("X", frame_id(noun, adj, "confirms"), frame_id(noun, adj, "claims"))
            ci = boot_ci(d)
            if m < 0.10: ok4 = False
            L.append(f"  {adj}-{noun}: mean {m:+.4f} CI[{ci[0]:+.3f},{ci[1]:+.3f}] positive {pos}/20")
    L.append(f"  -> factivity as a separate factor: {'MET' if ok4 else 'NOT MET'} (needs >= 0.10 under all four sources)")
    # registered second half of Q4: does the verb contrast vary across sources?
    vc = {}
    for noun in NOUNS:
        for adj in ADJ:
            vc[(noun, adj)] = [f(idx[(i, "X", frame_id(noun, adj, "confirms"))], "entA")
                               - f(idx[(i, "X", frame_id(noun, adj, "claims"))], "entA") for i in range(1, 21)]
    dd4 = [vc[("document", "plain")][k] - vc[("pamphlet", "disputed")][k] for k in range(20)]
    ci4 = boot_ci(dd4); m4 = statistics.mean(dd4)
    flat = abs(m4) < 0.10 and ci4[0] <= 0 <= ci4[1]
    L.append(f"  source x verb interaction (verb contrast under plain-document minus under disputed-pamphlet): "
             f"mean {m4:+.4f} CI[{ci4[0]:+.3f},{ci4[1]:+.3f}] -> "
             f"{'no interaction detected' if flat else 'INTERACTION: the verb effect depends on the source'}")

    L.append("Q5 polarity-blind contradiction cue on SUPPORTING content X (verb=states):")
    for noun in NOUNS:
        for adj in ADJ:
            fr = frame_id(noun, adj, "states")
            cell = [idx[(i, "X", fr)] for i in range(1, 21)]
            L.append(f"  {fr:<26} mean conB {statistics.mean(f(r, 'conB') for r in cell):.3f}   "
                     f"conB>=.15 in {sum(1 for r in cell if f(r, 'conB') >= 0.15)}/20")
    return "\n".join(L)


def main() -> None:
    if "--from-csv" in sys.argv:
        with open(OUT_CSV, encoding="utf-8") as fh:
            rows = list(csv.DictReader(fh))
        txt = summarize(rows); open(OUT_TXT, "w", encoding="utf-8").write(txt); print(txt)
        return
    cells = build_sentences()
    print(f"{len(cells)} sentences", flush=True)
    only = None
    if "--pass" in sys.argv:
        only = sys.argv[sys.argv.index("--pass") + 1]
    if only in (None, "A"):
        score_all(MODEL_A, cells, {"entA": "entailment", "neuA": "neutral", "conA": "contradiction"}, "A")
    if only in (None, "B"):
        score_all(MODEL_B, cells, {"entB": "entailment", "conB": "contradiction"}, "B")
    if only is not None:
        print(f"pass {only} complete; run with --pass {'B' if only == 'A' else 'A'} and then --merge")
        if not (os.path.exists(part_path("A")) and os.path.exists(part_path("B"))):
            return
        score_all(MODEL_A, cells, {"entA": "entailment", "neuA": "neutral", "conA": "contradiction"}, "A")
        score_all(MODEL_B, cells, {"entB": "entailment", "conB": "contradiction"}, "B")
    fields = ["item", "polarity", "noun", "adjective", "verb", "frame", "premise",
              "entA", "neuA", "conA", "entB", "conB"]
    with open(OUT_CSV, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore"); w.writeheader()
        for c in cells: w.writerow(c)
    txt = summarize(cells)
    open(OUT_TXT, "w", encoding="utf-8").write(txt)
    print(txt)
    print("Wrote", OUT_CSV, OUT_TXT)


if __name__ == "__main__":
    main()
